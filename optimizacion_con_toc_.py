# 1. PARÁMETROS TÉCNICOS (Basado en cccc.pdf)
# =================================================================
OPERACIONES = {
    'P1': [('A', 5), ('B', 3), ('A', 7), ('C', 3)],
    'P2': [('C', 2), ('A', 3), ('A', 8), ('B', 15)],
    'P3': [('C', 3), ('A', 5), ('B', 2)],
    'P4': [('C', 20), ('A', 1), ('B', 3), ('B', 11), ('C', 5)]
}

HORIZONTE_MINUTOS = 57600
MAX_WIP = 500
SETUP_TIME = 60

class MotorSimulacionTOC:
    def __init__(self, meta_semanal=206):
        self.reloj = 0
        self.meta_semanal = meta_semanal
        self.maquinas = {m: {'libre_en': 0, 'setup_actual': None, 'tarea_actual': None} for m in ['A', 'B', 'C']}
        self.colas = {m: [] for m in ['A', 'B', 'C']}
        self.piezas_en_sistema = []
        self.almacen_ensamble = {p: 0 for p in ['P1', 'P2', 'P3', 'P4']}
        self.unidades_enviadas = 0
        self.registros_gantt = []
        self.wip_historico = []
        self.piezas_lanzadas_semana = {p: 0 for p in ['P1', 'P2', 'P3', 'P4']}

    def ejecutar(self):
        while self.reloj < HORIZONTE_MINUTOS:
            semana_actual = (self.reloj // 7200) + 1

            # 1. Cuerda (Rope): Lanzamiento controlado
            for p_tipo in ['P1', 'P2', 'P3', 'P4']:
                if len(self.piezas_en_sistema) < MAX_WIP and self.piezas_lanzadas_semana[p_tipo] < self.meta_semanal:
                    nueva_pieza = {'tipo': p_tipo, 'op_idx': 0, 'id': f"{p_tipo}_{self.reloj}_{len(self.piezas_en_sistema)}"}
                    self.piezas_en_sistema.append(nueva_pieza)
                    self.piezas_lanzadas_semana[p_tipo] += 1
                    self.colas[OPERACIONES[p_tipo][0][0]].append(nueva_pieza)

            if self.reloj > 0 and self.reloj % 7200 == 0:
                self.piezas_lanzadas_semana = {p: 0 for p in ['P1', 'P2', 'P3', 'P4']}

            # 2. Despacho (Tambor)
            for m_id in ['B', 'A', 'C']:
                m_info = self.maquinas[m_id]
                if self.reloj >= m_info['libre_en'] and self.colas[m_id]:
                    # Priorizar mismo setup para evitar los 60 min
                    pieza = next((p for p in self.colas[m_id] if p['tipo'] == m_info['setup_actual']), self.colas[m_id][0])
                    self.colas[m_id].remove(piece := pieza)

                    setup_req = SETUP_TIME if piece['tipo'] != m_info['setup_actual'] and m_info['setup_actual'] is not None else 0
                    t_proc = OPERACIONES[piece['tipo']][piece['op_idx']][1]

                    m_info['libre_en'] = self.reloj + setup_req + t_proc
                    m_info['setup_actual'], m_info['tarea_actual'] = piece['tipo'], piece

                    self.registros_gantt.append({
                        'Machine': f"Máquina {m_id}", 'Task': f"{piece['id']}", 'Piece': piece['tipo'],
                        'Start': self.reloj, 'Finish': self.reloj + setup_req + t_proc,
                        'Week': semana_actual, 'Is_Setup': setup_req > 0
                    })

            # 3. Movimiento (Transferencia = 1)
            for m_id, m_info in self.maquinas.items():
                if m_info['tarea_actual'] and self.reloj == m_info['libre_en'] - 1:
                    p = m_info['tarea_actual']
                    p['op_idx'] += 1
                    m_info['tarea_actual'] = None
                    if p['op_idx'] < len(OPERACIONES[p['tipo']]):
                        self.colas[OPERACIONES[p['tipo']][p['op_idx']][0]].append(p)
                    else:
                        self.almacen_ensamble[p['tipo']] += 1
                        self.piezas_en_sistema.remove(p)

            # 4. Ensamble
            while all(self.almacen_ensamble[p] > 0 for p in ['P1', 'P2', 'P3', 'P4']):
                for p in ['P1', 'P2', 'P3', 'P4']: self.almacen_ensamble[p] -= 1
                self.unidades_enviadas += 1

            if self.reloj % 60 == 0: self.wip_historico.append(len(self.piezas_en_sistema))
            self.reloj += 1

